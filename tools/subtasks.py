         'сырья, Буфер забирает выход в ME (Логист делает и то и другое). Запас держит поддерживатель уровня. |',
         '| Руками | Мало крафтов и больше 9 видов на входе или важна раскладка | Собирать по одному в механизме. |',
         '',
         '## Подзадачи по эпохам\n',
         'Эпоха значит, к какому моменту подзадача должна работать. Подробный список предметов в `patterns.md` '
