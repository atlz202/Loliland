         '2. **Пять видов сборщиков делят одну группу на 512 штук:** молекулярный и улучшенный (3x3), большой X9 (9x9), '
         'нейтрониевый (сингулярности), сборщик синтеза и сборщик сборочного стола. У последних трёх свой кодировщик.',
