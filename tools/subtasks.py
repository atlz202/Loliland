def fmt(x):
    def two(v):
        d = 0 if v >= 10 else 1
        return f'{round(v, d):.{d}f}'.replace('.', ',')
    if x >= 1e6:
        return f'около {two(x / 1e6)} млн'
    if x >= 1e3:
        return f'около {two(x / 1e3)} тыс.'
    return f'около {round(x)}'


def size_word(n):
    return 'лёгкая' if n <= 30 else 'средняя' if n <= 100 else 'сложная'


def main():
    pats = json.load(open(os.path.join(ROOT, 'data/patterns.json'), encoding='utf8'))
    chains = json.load(open(os.path.join(ROOT, 'data/sub_milestones.json'), encoding='utf8'))

    by_era_enc = defaultdict(lambda: defaultdict(int))
    for p in pats:
        by_era_enc[p['era']][p['encoder']] += 1
    by_era_fam = defaultdict(lambda: defaultdict(list))
    for c in chains:
        by_era_fam[c['era']][c['family']].append(c)

    first_enc = {}
    for e in ERAS:
        for k in by_era_enc[e]:
            first_enc.setdefault(k, e)

    rows = []
    for e in ERAS:
        cnt = by_era_enc[e]
        total = sum(cnt.values())
        if total:
            parts = [f'{SHORT[k]}: {cnt[k]}' for k, _, _ in pt.ENCODERS if cnt[k]]
            rows.append(dict(era=e, stream=1, kind='кодирование', title=f'Закодировать шаблоны ({total})',
                             what=', '.join(parts) + '. Список в `patterns.md`.', difficulty=size_word(total)))
        for k, text in ASSEMBLER.items():
            if first_enc.get(k) == e:
                title, what = text
                rows.append(dict(era=e, stream=1, kind='сборщики', title=title, what=what, difficulty='средняя'))
        for f in FAM_ORDER:
            items = by_era_fam[e].get(f)
            if not items:
                continue
            stream, mode, how, diff = LINES[f]
            items.sort(key=lambda r: (-r['steps'], r['name']))
            ex = ', '.join(r['name'] for r in items[:4]) + (f' и ещё {len(items) - 4}' if len(items) > 4 else '')
            rows.append(dict(era=e, stream=stream, kind=mode, title=f'Линия «{f}» ({len(items)})',
                             what=f'{ex}. {how}', difficulty=diff))

    special = [p for p in pats if p['notes']]
    sp = defaultdict(lambda: dict(n=0, crafts=0.0, notes=set(), era=None, names=[]))
    for p in special:
        a = sp[p['machine']]
        a['n'] += 1
        a['crafts'] += p['crafts']
        a['notes'].update(p['notes'])
        a['names'].append(p['name'])
        if a['era'] is None or ERAS.index(p['era']) < ERAS.index(a['era']):
            a['era'] = p['era']

    total_pats = len(pats)
    pre = sum(1 for p in pats if p['era'] != 'Остальные пять вех')
