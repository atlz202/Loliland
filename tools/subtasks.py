         '(проверено по коду мода), а в ME есть жидкостные и газовые ячейки. Шаблон обработки держит 9 входов и 3 выхода.',
         '4. **Программы на компьютерах для цепочек не нужны.** Больше 9 видов на входе бывает только у душ драконов и '
         'пчелиной фабрики, их нужно около 140 крафтов на всё, проще руками. Под вопросом раскладка у продвинутого QED '
         'и легендарного сборочного комплекса, это проверка в первый час.',
         '5. **Узкие места по скорости,** которые надо замерить в первый час: синтез (около 460 тыс. демонических слитков на '
         'все вехи), продвинутый QED (около 5,6 млн хроматических слитков), реакционные камеры Techguns (около 6,5 млн '
