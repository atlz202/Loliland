// Полный сценарий в настоящем браузере: четыре игрока собирают команду, раздают роли и ведут задания.
//
// Запуск (нужны эмуляторы и сайт в локальном режиме, см. README):
//   npm run emulators        в одном окне
//   npm run dev:local        в другом
//   node tests/e2e/scenario.mjs
//
// Скриншоты складываются в tests/e2e/shots (папка не попадает в репозиторий).
import { BASE, check, chromium, fillRegistration, login, newPlayer, problems, register, resetEmulators, shot } from './lib.mjs'

const step = (title) => console.log(`\n${title}`)
const settle = (p, ms = 500) => p.page.waitForTimeout(ms)
const member = (p, nick) => p.page.locator(`li[data-member="${nick}"]`)
const role = (p, id) => p.page.locator(`[data-role="${id}"]`)
const card = (p, id) => p.page.locator(`.tcard[data-task="${id}"]`)
const tab = (p, name) => p.page.locator('.tabs.big button', { hasText: name })

await resetEmulators()
const browser = await chromium.launch()

try {
  // ---------- Сбор команды ----------
  step('1. Капитан регистрируется и создаёт команду')
  const cap = await newPlayer(browser, 'Cap_Alex')
  await register(cap)
  await cap.page.getByRole('button', { name: 'Найти команду' }).first().click()
  await cap.page.getByRole('button', { name: 'Создать', exact: true }).click()
  await cap.page.getByLabel('Название команды').fill('Пчёлки')
  await cap.page.getByRole('button', { name: 'Создать команду' }).click()
  const teamId = (await cap.page.locator('.team-id.big').textContent()).trim()
  check(/^[A-HJ-NP-Z2-9]{6}$/.test(teamId), `у команды есть ID: ${teamId}`)
  await cap.page.getByRole('button', { name: 'Открыть команду' }).click()
  await cap.page.waitForURL(`**/team/${teamId}`)
  await card(cap, 1).waitFor()
  check((await cap.page.locator('.tcard').count()) === 84, 'в дереве 84 задания')
  await settle(cap, 800)
  check((await cap.page.locator('.board-svg path.dep').count()) === 70, 'нарисовано 70 связей')
  await shot(cap, '01-team-gathering')

  step('2. Второй игрок входит по ID')
  const bee = await newPlayer(browser, 'Bee_Mira')
  await register(bee)
  await bee.page.getByRole('button', { name: 'Найти команду' }).first().click()
  await bee.page.getByLabel('ID команды').fill(teamId.toLowerCase())
  await bee.page.locator('form button').click()
  await bee.page.waitForURL(`**/team/${teamId}`)
  await member(cap, 'Bee_Mira').waitFor()
  check(true, 'капитан сразу видит нового участника')

  step('3. Третий приходит по одноразовой ссылке, ещё без аккаунта')
  await cap.page.getByRole('button', { name: 'Управление командой' }).click()
  await cap.page.getByRole('button', { name: 'Создать ссылку' }).click()
  const linkInput = cap.page.getByLabel('Ссылка-приглашение').first()
  await linkInput.waitFor()
  const link = (await linkInput.inputValue()).replace(/^https?:\/\/[^/]+/, BASE)
  check(/\/join\/[A-Z0-9]{6}\/[A-Za-z0-9]{20}$/.test(link), 'ссылка создана')

  const drak = await newPlayer(browser, 'Drakon_77')
  await drak.page.goto(link)
  await drak.page.getByRole('heading', { name: 'Тебя зовут в команду' }).waitFor()
  await shot(drak, '02-join-guest')
  await drak.page.getByRole('link', { name: 'Зарегистрироваться' }).click()
  await fillRegistration(drak)
  await drak.page.waitForURL('**/join/**')
  await drak.page.getByRole('heading', { name: 'Пчёлки' }).waitFor()
  check(true, 'после регистрации человек вернулся к приглашению')
  await shot(drak, '03-join-ready')
  await drak.page.getByRole('button', { name: 'Вступить в команду' }).click()
  await drak.page.waitForURL(`**/team/${teamId}`)
  await cap.page.getByText('использована').waitFor()
  check(true, 'одноразовая ссылка сгорела')

  step('4. Четвёртого зовут лично, а по сгоревшей ссылке он войти не может')
  const quest = await newPlayer(browser, 'Questy')
  await register(quest)
  await quest.page.goto(link)
  await quest.page.getByText('уже вошли столько раз').waitFor()
  check(true, 'сгоревшая ссылка не пускает')
  await cap.page.getByLabel('Ник игрока').fill('que')
  await cap.page.locator('.found li', { hasText: 'Questy' }).getByRole('button', { name: 'Пригласить' }).click()
  await cap.page.getByText('Приглашены и ещё не ответили').waitFor()
  await settle(cap)
  await shot(cap, '04-manage-dialog')
  await quest.page.goto(`${BASE}/cabinet`)
  await quest.page.getByRole('heading', { name: 'Приглашения' }).waitFor()
  await shot(quest, '05-cabinet-invitation')
  await quest.page.getByRole('button', { name: 'Вступить' }).click()
  await quest.page.waitForURL(`**/team/${teamId}`)
  await member(cap, 'Questy').waitFor()
  check((await cap.page.locator('.members > li').count()) === 4, 'в команде четверо')

  step('5. Капитан закрывает вход и проверяет, что по ID больше не войти')
  await cap.page.getByRole('button', { name: 'Закрыть вход' }).click()
  await cap.page.getByRole('button', { name: 'Открыть снова' }).waitFor()
  const late = await newPlayer(browser, 'Late_One')
  await register(late)
  await late.page.getByRole('button', { name: 'Найти команду' }).first().click()
  await late.page.getByLabel('ID команды').fill(teamId)
  await late.page.locator('form button').click()
  await late.page.getByText('Команда закрыта').waitFor()
  check(true, 'в закрытую команду по ID не пускает')
  await late.context.close()
  await cap.page.keyboard.press('Escape')

  // ---------- Роли ----------
  step('6. Раздача ролей: перетаскивание на себя и нажатие')
  check((await bee.page.locator('.palette').count()) === 0, 'до старта раздачи ролей палитры нет')
  await cap.page.getByRole('button', { name: 'Начать распределение ролей' }).click()
  await role(bee, 'beekeeper').waitFor()
  await role(bee, 'beekeeper').dragTo(member(bee, 'Bee_Mira'))
  await member(bee, 'Bee_Mira').getByText('Пчеловод').waitFor()
  check(true, 'роль встала после перетаскивания на себя')
  await role(bee, 'beemech').click()
  await role(bee, 'ragu').click()
  await role(drak, 'dragon').dragTo(member(drak, 'Drakon_77'))
  await role(drak, 'multi').click()
  await role(quest, 'quest').dragTo(member(quest, 'Questy'))
  await role(quest, 'misc').click()
  for (const id of ['ae', 'coder', 'ind1', 'meka']) await role(cap, id).click()
  await member(cap, 'Cap_Alex').getByText('Мека').waitFor()

  // Чужому роль перетащить нельзя, а капитану можно.
  await role(bee, 'ind2').dragTo(member(bee, 'Drakon_77'))
  await settle(bee)
  check((await member(bee, 'Drakon_77').getByText('Ind-2').count()) === 0, 'участник не может дать роль другому')
  await role(cap, 'ind2').dragTo(member(cap, 'Questy'))
  await member(cap, 'Questy').getByText('Ind-2').waitFor()
  check(true, 'капитан может дать роль любому')

  // Квестовик только один.
  await role(bee, 'quest').click()
  await bee.page.getByText('Квестовик уже занят').waitFor()
  check(true, 'второго квестовика взять нельзя')
  await bee.page.getByRole('button', { name: 'скрыть' }).click()

  await settle(bee, 900)
  check((await bee.page.locator('.tcard.lit').count()) > 5, 'во время раздачи виден предварительный расклад')
  await shot(bee, '06-roles-phase')

  step('7. Капитан нажимает «Распределение завершено»')
  await cap.page.getByRole('button', { name: 'Распределение завершено' }).click()
  await cap.page.getByRole('heading', { name: 'Завершить распределение?' }).waitFor()
  await shot(cap, '07-finish-confirm')
  await cap.page.getByRole('button', { name: 'Завершить', exact: true }).click()
  await cap.page.locator('.badge.phase-running').waitFor()
  await bee.page.locator('.badge.phase-running').waitFor()
  await settle(cap, 900)
  check((await cap.page.locator('.tcard.framed').count()) === 84, 'у каждого задания есть исполнитель')
  const capSteps = await cap.page.locator('.tcard-step').count()
  check(capSteps > 10, `у капитана показан путь: ${capSteps} шагов`)
  check((await cap.page.locator('.route').count()) > 5, 'путь нарисован стрелками')
  await shot(cap, '08-tree-captain')

  // ---------- Работа ----------
  step('8. Пчеловод открывает своё задание, отмечает подпункты и закрывает его')
  await settle(bee, 600)
  await shot(bee, '09-tree-beekeeper')
  await card(bee, 17).scrollIntoViewIfNeeded()
  await card(bee, 17).click()
  const dialog = bee.page.locator('.task-dialog')
  await dialog.waitFor()
  await settle(bee, 400)
  await shot(bee, '10-task-dialog')
  const boxes = dialog.locator('.subtasks input')
  const subtasks = await boxes.count()
  check(subtasks >= 2, `в задании ${subtasks} подпунктов`)
  await boxes.nth(0).check()
  await dialog.locator('.status.s-doing').waitFor()
  check(true, 'первый подпункт сам перевёл задание «в работу»')
  await boxes.nth(1).check()
  await dialog.getByRole('button', { name: 'Готово' }).click()
  await dialog.locator('.status.s-done').waitFor()
  check((await dialog.locator('.subtasks input:checked').count()) === subtasks, '«Готово» отметило все подпункты')
  await bee.page.keyboard.press('Escape')
  await card(cap, 17).locator('.tcard-state.s-done').waitFor()
  check(true, 'капитан видит у себя, что задание готово')

  step('9. Чужое задание отмечать нельзя, капитану можно любое')
  await card(bee, 14).scrollIntoViewIfNeeded()
  await card(bee, 14).click()
  await dialog.getByText('отмечают его исполнители и капитан').waitFor()
  check((await dialog.locator('.subtasks input:enabled').count()) === 0, 'у чужого задания подпункты не нажимаются')
  await bee.page.keyboard.press('Escape')
  await card(cap, 14).scrollIntoViewIfNeeded()
  await card(cap, 14).click()
  await cap.page.locator('.task-dialog').getByRole('button', { name: 'Взять в работу' }).click()
  await cap.page.locator('.task-dialog .status.s-doing').waitFor()
  await cap.page.keyboard.press('Escape')
  check(true, 'капитан отметил задание драконика')

  step('10. Вкладка «Мои задачи»')
  await tab(bee, 'Мои задачи').click()
  await bee.page.locator('.mytask').first().waitFor()
  check((await bee.page.getByRole('heading', { name: /Сделано/ }).count()) === 1, 'есть раздел «Сделано»')
  const take = bee.page.locator('.mytask-act button', { hasText: 'Взять' }).first()
  await take.click()
  await bee.page.getByRole('heading', { name: /В работе/ }).waitFor()
  await settle(bee)
  await shot(bee, '11-my-tasks', { fullPage: true })

  step('11. Вкладка «Квесты»: этапы ведёт квестовик')
  await tab(quest, 'Квесты').click()
  const artifacts = quest.page.locator('.quest', { hasText: 'Артефакты' }).first()
  await artifacts.getByRole('button', { name: 'Готов к сдаче' }).click()
  await artifacts.locator('.stages button.active', { hasText: 'Готов к сдаче' }).waitFor()
  await artifacts.getByRole('button', { name: 'Сдан', exact: true }).click()
  await quest.page.locator('.quest.st-3', { hasText: 'Артефакты' }).waitFor()
  await settle(quest)
  await shot(quest, '12-quests')
  await tab(bee, 'Квесты').click()
  await bee.page.locator('.quest.st-3', { hasText: 'Артефакты' }).waitFor()
  check((await bee.page.locator('.stages button:enabled').count()) === 0, 'не квестовик этапы менять не может')
  check((await bee.page.getByText(/Сдано\s*1\s*из 27/).count()) === 1, 'счётчик квестов обновился у всех')

  step('12. Квестовик видит свои квестовые задания отдельно')
  await tab(quest, 'Мои задачи').click()
  await quest.page.getByRole('heading', { name: /Квестовые задания/ }).waitFor()
  await shot(quest, '13-my-tasks-quest-runner', { fullPage: true })
  check(true, 'квестовые задания идут отдельным списком')

  // ---------- Перераспределение и состав ----------
  step('13. Капитан меняет роли: отметки сохраняются')
  await cap.page.getByRole('button', { name: 'Изменить роли' }).click()
  await cap.page.getByRole('button', { name: 'Изменить роли' }).last().click()
  await cap.page.locator('.badge.phase-roles').waitFor()
  await role(cap, 'ind2').dragTo(member(cap, 'Cap_Alex'))
  await member(cap, 'Cap_Alex').getByText('Ind-2').waitFor()
  await cap.page.getByRole('button', { name: 'Распределение завершено' }).click()
  await cap.page.getByRole('button', { name: 'Завершить', exact: true }).click()
  await cap.page.locator('.badge.phase-running').waitFor()
  await card(cap, 17).locator('.tcard-state.s-done').waitFor()
  check(true, 'после перераспределения готовое задание осталось готовым')

  step('14. Игрок выходит, капитан видит предупреждение и исключает ещё одного')
  await drak.page.getByRole('button', { name: 'Выйти из команды' }).click()
  await drak.page.getByRole('dialog').getByRole('button', { name: 'Выйти' }).click()
  await drak.page.waitForURL('**/cabinet')
  await cap.page.getByText('остались без исполнителя').waitFor()
  check(true, 'капитан видит, что задания остались без исполнителя')
  await settle(cap)
  await shot(cap, '14-drift-warning')
  await cap.page.getByRole('button', { name: 'Управление командой' }).click()
  await cap.page.locator('.found li', { hasText: 'Questy' }).getByRole('button', { name: 'Исключить' }).click()
  await cap.page.getByRole('button', { name: 'Исключить' }).last().click()
  await quest.page.getByText('Ты не в этой команде').waitFor()
  check(true, 'исключённый игрок больше не видит команду')

  step('15. Капитан передаёт капитана')
  await cap.page.locator('.found li', { hasText: 'Bee_Mira' }).getByRole('button', { name: 'Сделать капитаном' }).click()
  await cap.page.getByRole('button', { name: 'Передать' }).click()
  await bee.page.getByRole('button', { name: 'Управление командой' }).waitFor()
  await cap.page.getByRole('button', { name: 'Выйти из команды' }).waitFor()
  check(true, 'новый капитан получил управление, прежний стал участником')

  step('16. Телефон: страница команды помещается по ширине')
  const phone = await newPlayer(browser, 'Bee_Mira', { width: 390, height: 844 })
  await login(phone)
  await phone.page.goto(`${BASE}/team/${teamId}`)
  await card(phone, 1).waitFor()
  await settle(phone, 800)
  const overflow = await phone.page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  check(overflow <= 1, `на телефоне страница не уезжает вбок (лишних пикселей: ${overflow})`)
  await shot(phone, '15-phone', { fullPage: true })

  // ---------- Приглашение поверх закрытого входа и роспуск ----------
  step('17. Приглашённый лично входит по ID даже в закрытую команду, и приглашение гаснет')
  await bee.page.getByRole('button', { name: 'Управление командой' }).click()
  const manage = bee.page.locator('.manage')
  await manage.getByLabel('Ник игрока').fill('lat')
  await manage.locator('.found li', { hasText: 'Late_One' }).getByRole('button', { name: 'Пригласить' }).click()
  await manage.getByText('Приглашены и ещё не ответили').waitFor()
  const late2 = await newPlayer(browser, 'Late_One')
  await login(late2)
  await late2.page.getByRole('heading', { name: 'Приглашения' }).waitFor()
  await late2.page.getByRole('button', { name: 'Найти команду' }).first().click()
  await late2.page.getByLabel('ID команды').fill(teamId)
  await late2.page.locator('form button').click()
  await late2.page.waitForURL(`**/team/${teamId}`)
  check(true, 'по ID в закрытую команду пустило, потому что есть личное приглашение')
  await manage.getByText('Приглашены и ещё не ответили').waitFor({ state: 'detached' })
  await late2.page.goto(`${BASE}/cabinet`)
  await late2.page.getByRole('heading', { name: 'Late_One' }).waitFor()
  await settle(late2)
  check((await late2.page.getByRole('heading', { name: 'Приглашения' }).count()) === 0, 'приглашение погасло и у игрока, и у капитана')

  step('18. Капитан остаётся один и распускает команду')
  await manage.getByLabel('Ник игрока').fill('')
  check((await manage.getByRole('button', { name: 'Распустить команду' }).count()) === 0, 'пока в команде есть другие, распустить её нельзя')
  for (const nick of ['Late_One', 'Cap_Alex']) {
    await manage.locator('.found li', { hasText: nick }).getByRole('button', { name: 'Исключить' }).click()
    await bee.page.getByRole('button', { name: 'Исключить', exact: true }).last().click()
    await manage.locator('.found li', { hasText: nick }).waitFor({ state: 'detached' })
  }
  await manage.getByRole('button', { name: 'Распустить команду' }).click()
  await settle(bee, 300)
  await shot(bee, '16-disband-confirm')
  await bee.page.getByRole('button', { name: 'Распустить', exact: true }).click()
  await bee.page.waitForURL('**/cabinet')
  await bee.page.getByRole('heading', { name: 'Bee_Mira' }).waitFor()
  await settle(bee)
  check((await bee.page.getByText('Пчёлки').count()) === 0, 'команды больше нет в кабинете капитана')
  await cap.page.getByRole('heading', { name: 'Команда не найдена' }).waitFor()
  await phone.page.getByRole('heading', { name: 'Команда не найдена' }).waitFor()
  check(true, 'у остальных страница команды показывает, что её больше нет')

  console.log(problems.length ? `\nОшибки в браузере:\n${problems.join('\n')}` : '\nОшибок в браузере нет.')
  console.log('\nСценарий прошёл целиком.')
} finally {
  await browser.close()
}
